let currentLang = sessionStorage.getItem('cannabox_lang') || null;
let disclaimerAccepted = sessionStorage.getItem('cannabox_disclaimer') === 'true';

function selectLanguage(lang) {
    currentLang = lang;
    sessionStorage.setItem('cannabox_lang', lang);

    const langModal = document.getElementById('languageModal');
    if (langModal) {
        langModal.style.opacity = '0';
        langModal.style.pointerEvents = 'none';
        setTimeout(() => {
            langModal.classList.add('hidden');
        }, 300);
    }

    setTimeout(() => {
        showDisclaimerModal();
        updateContent();
        if (typeof renderMachines === 'function') renderMachines();
        if (typeof initMachineDetail === 'function') initMachineDetail();
    }, 350);
}

function switchLanguage(lang) {
    currentLang = lang;
    sessionStorage.setItem('cannabox_lang', lang);
    updateContent();
    updateActiveLangButton();

    if (typeof renderMachines === 'function') renderMachines();
    if (typeof initMachineDetail === 'function') initMachineDetail();
    if (typeof renderProducts === 'function' && typeof currentCategory !== 'undefined' && currentCategory) {
        renderProducts(currentCategory);
    }
}

function updateActiveLangButton() {
    const huBtn = document.getElementById('btn-hu');
    const enBtn = document.getElementById('btn-en');

    if (huBtn && enBtn && currentLang) {
        if (currentLang === 'hu') {
            huBtn.className = 'px-4 py-2 rounded-lg text-sm font-semibold transition-all bg-emerald-500 text-black shadow-lg shadow-emerald-950/40';
            enBtn.className = 'px-4 py-2 rounded-lg text-sm font-semibold transition-all text-gray-400 hover:text-white';
        } else {
            enBtn.className = 'px-4 py-2 rounded-lg text-sm font-semibold transition-all bg-emerald-500 text-black shadow-lg shadow-emerald-950/40';
            huBtn.className = 'px-4 py-2 rounded-lg text-sm font-semibold transition-all text-gray-400 hover:text-white';
        }
    }
}

function updateContent() {
    const activeLang = currentLang || 'en';
    const t = translations[activeLang];
    if (!t) return;

    const elements = document.querySelectorAll('[id]');
    elements.forEach(el => {
        const key = el.id;
        if (key === 'disclaimerText' || key === 'disclaimerContent' || key === 'languageModal' || key === 'disclaimerModal') return;
        if (t[key] !== undefined) {
            if (key === 'heroTitle') {
                el.innerHTML = t[key];
            } else {
                el.textContent = t[key];
            }
        }
    });

    updateActiveLangButton();
}

function showDisclaimerModal() {
    ensureDisclaimerModal();

    const modal = document.getElementById('disclaimerModal');
    if (modal && !disclaimerAccepted) {
        const activeLang = currentLang || 'en';
        const t = translations[activeLang];
        if (t) {
            const titleEl = document.getElementById('disclaimerTitle');
            const textEl = document.getElementById('disclaimerText');
            const checkLabel = document.getElementById('checkboxLabel');
            const enterBtnEl = document.getElementById('enterBtn');
            const scrollHint = document.getElementById('disclaimerScrollHint');

            if (titleEl) titleEl.textContent = t.disclaimerTitle;
            if (textEl) textEl.innerHTML = t.disclaimerText;
            if (checkLabel) checkLabel.textContent = t.checkboxLabel;
            if (enterBtnEl) enterBtnEl.textContent = t.enterBtn;
            if (scrollHint) scrollHint.textContent = t.disclaimerScrollHint;
        }

        modal.classList.remove('hidden', 'pointer-events-none');
        modal.offsetHeight; // force reflow
        modal.style.opacity = '1';
        modal.style.pointerEvents = 'auto';
        if (typeof initDisclaimerScroll === 'function') {
            initDisclaimerScroll();
        }
    }
}

function initLanguage() {
    ensureLanguageModal();
    ensureDisclaimerModal();

    if (!currentLang) {
        const modal = document.getElementById('languageModal');
        if (modal) {
            modal.classList.remove('hidden');
            modal.offsetHeight;
            modal.style.opacity = '1';
            modal.style.pointerEvents = 'auto';
        }

        if (typeof renderMachines === 'function') renderMachines();
        if (typeof initMachineDetail === 'function') initMachineDetail();
        updateContent();
        return;
    }

    const langModal = document.getElementById('languageModal');
    if (langModal) {
        langModal.classList.add('hidden');
        langModal.style.opacity = '0';
        langModal.style.pointerEvents = 'none';
    }

    updateContent();
    updateActiveLangButton();

    if (!disclaimerAccepted) {
        showDisclaimerModal();
    }

    if (typeof renderMachines === 'function') renderMachines();
    if (typeof initMachineDetail === 'function') initMachineDetail();
}

document.addEventListener('DOMContentLoaded', initLanguage);

